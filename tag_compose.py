def _strip(s, table):
    for k in sorted(table, key=len, reverse=True):
        if s == k:
            return table[k], ""
        if s.startswith(k + " "):
            return table[k], s[len(k) + 1:]
    return None, s

def _strip_tail(s, table):
    for k in sorted(table, key=len, reverse=True):
        if s == k:
            return table[k], ""
        if s.endswith(" " + k):
            return table[k], s[:-(len(k) + 1)]
    return None, s

